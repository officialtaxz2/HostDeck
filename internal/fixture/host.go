// Platte des nachgebauten Servers, wie df sie meldet.
const (
	DiskTotal int64 = 193_000_000_000
	DiskFree  int64 = 99_000_000_000
)

// Statfs gibt die feste Plattengröße zurück, damit Tests nicht vom
// Rechner abhängen, auf dem sie laufen.
func Statfs(string) (int64, int64, error) { return DiskTotal, DiskFree, nil }

func sum(s string) string {
	h := md5.Sum([]byte(s))
	return hex.EncodeToString(h[:])
}

// buildHost legt an, was außerhalb von Docker auf dem Server liegt: Home-
// Ordner, Cronjobs, eigene Dienste, Einstellungen und die Paketdatenbank.
func buildHost(t testing.TB, root string) {
	t.Helper()
	write := func(p, content string, mode os.FileMode) {
		full := filepath.Join(root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), mode); err != nil {
			t.Fatal(err)
		}
	}
	link := func(target, p string) {
		full := filepath.Join(root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(target, full); err != nil {
			t.Fatal(err)
		}
	}

	// Home-Ordner
	write("/root/.ssh/authorized_keys", "ssh-ed25519 AAAAgeheim1 demo@pc\n# alt\nssh-ed25519 AAAAgeheim2 handy\n", 0o600)
	write("/root/.ssh/id_ed25519", "PRIVAT-GEHEIM\n", 0o600)
	write("/root/.ssh/id_ed25519.pub", "ssh-ed25519 AAAAgeheim3 root@vps1\n", 0o644)
	write("/root/.docker/config.json", `{"auths":{"ghcr.io":{"auth":"Z2VoZWltLWdoY3I="}}}`, 0o600)
	write("/root/backup.sh", "#!/bin/sh\n", 0o755)
	write("/root/notizen.txt", "Server-Notizen\n", 0o644)
	write("/root/.cache/pip/x", strings.Repeat("c", 1_200_000), 0o644)
	write("/root/.vscode-server/bin/x", strings.Repeat("v", 1_200_000), 0o644)
	write("/root/hostdeck", "ELF", 0o755)
	write("/root/hostdeck-linux-amd64", "ELF", 0o755)
	write("/home/demo/.cache/klein", strings.Repeat("k", 4096), 0o644)
	write("/root/.bashrc", "# bashrc\n", 0o644)
	write("/home/demo/.bashrc", "# bashrc\n", 0o644)
	write("/home/demo/Dokumente/plan.txt", "Plan\n", 0o644)

	// Webseiten: die Standardseite von nginx zählt nicht.
	write("/var/www/html/index.nginx-debian.html", "<h1>Welcome to nginx!</h1>\n", 0o644)
	write("/var/www/alte-seite/index.html", "<h1>Alt</h1>\n", 0o644)

	// /usr/local/bin: eigenes Programm, Download, npm-Installation, Paketdatei
	write("/usr/local/bin/hostdeck-sync", "#!/bin/sh\n", 0o755)
	write("/usr/local/bin/docker-compose", "ELF", 0o755)
	write("/usr/local/lib/node_modules/pm2/bin/pm2", "#!/usr/bin/env node\n", 0o755)
	link("../lib/node_modules/pm2/bin/pm2", "/usr/local/bin/pm2")
	link("/usr/local/lib/hostdeck/hostdeck", "/usr/local/bin/hostdeck") // von hostdeck einrichten
	write("/usr/local/bin/paket-tool", "ELF", 0o755)

	// Cron: Crontab von root, eigene Datei in cron.d, Paketdatei, Standard-/etc/crontab
	write("/var/spool/cron/crontabs/root", "# DO NOT EDIT THIS FILE\nMAILTO=geheim-mail@example.org\n"+
		"0 3 * * * PGPASSWORD=geheim-pg pg_dump -h localhost app > /root/app.sql\n"+
		"@reboot /root/backup.sh\n", 0o600)
	etcCrontab := "SHELL=/bin/sh\n17 *\t* * *\troot\tcd / && run-parts --report /etc/cron.hourly\n"
	write("/etc/crontab", etcCrontab, 0o644)
	write("/etc/cron.d/caddy-reload", "30 4 * * 1 root systemctl reload caddy\n", 0o644)
	e2scrub := "10 3 * * 0 root test -e /run/systemd/system || SERVICE_MODE=1 /usr/lib/x86_64-linux-gnu/e2fsprogs/e2scrub_all_cron\n"
	write("/etc/cron.d/e2scrub_all", e2scrub, 0o644)
	write("/etc/cron.daily/dpkg", "#!/bin/sh\n", 0o755)
	write("/etc/cron.daily/aufraeumen", "#!/bin/sh\ndocker system prune -f\n", 0o755)

	// systemd: eigener Dienst mit Timer, Docker-Anpassung, snapd-Unit, Verweis
	write("/etc/systemd/system/hostdeck-sync.service", "[Unit]\nDescription=Sync zum PC\n[Service]\nType=oneshot\n"+
		"Environment=TOKEN=geheim-sync\nExecStart=/usr/local/bin/hostdeck-sync --token geheim-flag /opt\n", 0o644)
	write("/etc/systemd/system/hostdeck-sync.timer", "[Unit]\nDescription=Sync nachts\n[Timer]\nOnCalendar=*-*-* 02:30:00\n[Install]\nWantedBy=timers.target\n", 0o644)
	link("/etc/systemd/system/hostdeck-sync.timer", "/etc/systemd/system/timers.target.wants/hostdeck-sync.timer")
	write("/etc/systemd/system/snap-core22-1234.mount", "[Mount]\nWhat=/var/lib/snapd/snaps/core22_1234.snap\n", 0o644)
	link("/usr/lib/systemd/system/caddy.service", "/etc/systemd/system/multi-user.target.wants/caddy.service")
	write("/etc/systemd/system/docker.service.d/override.conf", "[Service]\nLimitNOFILE=1048576\n", 0o644)

	// Einstellungen
	sshdDefault := "Include /etc/ssh/sshd_config.d/*.conf\nKbdInteractiveAuthentication no\nUsePAM yes\n"
	write("/etc/ssh/sshd_config", sshdDefault+"PermitRootLogin prohibit-password\n", 0o644)
	write("/etc/ssh/sshd_config.d/50-cloud-init.conf", "PasswordAuthentication no\n", 0o644)
	write("/etc/ssh/ssh_host_ed25519_key", "geheim-hostkey\n", 0o600)
	ufwDefault := "ENABLED=no\nLOGLEVEL=low\n"
	write("/etc/ufw/ufw.conf", "ENABLED=yes\nLOGLEVEL=low\n", 0o644)
	write("/etc/ufw/user.rules", "*filter\n### tuple ### allow tcp 22 0.0.0.0/0 any 0.0.0.0/0 in\n-A ufw-user-input -p tcp --dport 22 -j ACCEPT\n"+
		"### tuple ### allow tcp 80,443 0.0.0.0/0 any 0.0.0.0/0 in\n### tuple ### allow udp 19132:19133 0.0.0.0/0 any 0.0.0.0/0 in\nCOMMIT\n", 0o640)
	write("/etc/ufw/user6.rules", "### tuple ### allow tcp 22 ::/0 any ::/0 in\n", 0o640)
	write("/etc/docker/daemon.json", `{"log-driver":"json-file","log-opts":{"max-size":"10m"}}`, 0o644)
	write("/etc/passwd", "root:x:0:0:root:/root:/bin/bash\nsyslog:x:104:110::/home/syslog:/usr/sbin/nologin\n"+
		"demo:x:1000:1000:Demo:/home/demo:/bin/bash\nnobody:x:65534:65534:nobody:/nonexistent:/usr/sbin/nologin\n"+
		"caddy:x:998:997:Caddy web server:/var/lib/caddy:/usr/sbin/nologin\n", 0o644)
	write("/var/lib/caddy/.local/share/caddy/certificates/acme-v02.api.letsencrypt.org-directory/shop.example.net/shop.example.net.key", "geheim-zertifikat\n", 0o600)
	write("/etc/group", "root:x:0:\nsudo:x:27:demo\ndocker:x:999:demo\ndemo:x:1000:\n", 0o644)
	write("/etc/shadow", "root:geheim-hash:19000:0:99999:7:::\n", 0o640)
	write("/etc/timezone", "Europe/Berlin\n", 0o644)
	write("/etc/fstab", "LABEL=cloudimg-rootfs / ext4 discard,errors=remount-ro 0 1\n/swapfile none swap sw 0 0\n"+
		"//nas/backup /mnt/nas cifs credentials=/root/.smb-geheim,uid=0 0 0\n", 0o644)
	write("/etc/apt/sources.list.d/caddy-stable.list", "deb [signed-by=/usr/share/keyrings/caddy.gpg] https://dl.cloudsmith.io/public/caddy/stable/deb/debian any-version main\n", 0o644)
	write("/etc/apt/sources.list.d/ubuntu.sources", "Types: deb\nURIs: http://archive.ubuntu.com/ubuntu/\nSuites: noble\n", 0o644)
	write("/etc/pam.d/common-auth", "auth required pam_unix.so\n", 0o644)
	// Gehört zur Maschine oder legen Paketskripte an: nicht in der Liste
	write("/etc/crypttab", "# <target name>\t<source device>\n", 0o644)
	write("/etc/default/grub", "GRUB_DEFAULT=0\nGRUB_CMDLINE_LINUX=\"console=ttyS0\"\n", 0o644)
	write("/etc/mdadm/mdadm.conf", "HOMEHOST <system>\n", 0o644)
	write("/etc/inputrc", "set bell-style none\n", 0o644)
	write("/etc/sysctl.d/99-cloudimg-ipv6.conf", "net.ipv6.conf.all.use_tempaddr = 0\n", 0o644)
	// Kernel-Einstellungen: geändert, eigene Datei, unveränderte Paketdatei
	sysctlDefault := "# /etc/sysctl.conf\n#net.ipv4.ip_forward=1\n"
	write("/etc/sysctl.conf", sysctlDefault+"net.ipv4.ip_forward=1\nvm.swappiness = 10\n", 0o644)
	write("/etc/sysctl.d/99-eigene.conf", "# fuer viele Dateien\nfs.inotify.max_user_watches=524288\n", 0o644)
	netsec := "net.ipv4.conf.default.rp_filter=2\n"
	write("/etc/sysctl.d/10-network-security.conf", netsec, 0o644)
	link("../sysctl.conf", "/etc/sysctl.d/99-sysctl.conf")
	// Debian legt Verweise auf den Kernel direkt unter / an.
	write("/boot/vmlinuz-6.12.48-amd64", "kernel", 0o644)
	link("boot/vmlinuz-6.12.48-amd64", "/vmlinuz")
	link("boot/vmlinuz-6.12.48-amd64", "/vmlinuz.old")
	link("boot/initrd.img-6.12.48-amd64", "/initrd.img")
	link("boot/initrd.img-6.12.48-amd64", "/initrd.img.old")

	// Swap und ein eigener Ordner direkt unter /
	write("/proc/swaps", "Filename\t\t\t\tType\t\tSize\t\tUsed\t\tPriority\n/swapfile                               file\t\t4194300\t\t0\t\t-2\n", 0o444)
	write("/swapfile", strings.Repeat("s", 16384), 0o600)
	write("/minecraft-alt/world/level.dat", strings.Repeat("m", 8192), 0o644)
	write("/usr/bin/bash", strings.Repeat("b", 8192), 0o755)
	write("/var/log/syslog", strings.Repeat("l", 4096), 0o644)

	// Paketverlauf: zwei Installationen, eine Reparatur, ein entferntes Paket
	write("/var/log/apt/history.log", "\nStart-Date: 2026-03-01\nCommandline: apt install -y caddy ufw htop\nEnd-Date: 2026-03-01\n"+
		"\nCommandline: apt-get install -y linux-generic-hwe-24.04 grub-pc qemu-guest-agent\n"+
		"\nCommandline: apt-get install --reinstall bash\n", 0o644)
	var gz bytes.Buffer
	zw := gzip.NewWriter(&gz)
	zw.Write([]byte("Commandline: apt-get install git nginx\nCommandline: /usr/bin/unattended-upgrade\n"))
	zw.Close()
	write("/var/log/apt/history.log.1.gz", gz.String(), 0o644)

	// Paketdatenbank
	type pkg struct {
		name      string
		files     []string
		conffiles map[string]string // Pfad -> Inhalt, wie das Paket ihn mitbringt
	}
	pkgs := []pkg{
		{"base-files", []string{"/etc/os-release"}, nil},
		{"bash", []string{"/usr/bin/bash"}, nil},
		{"caddy", []string{"/usr/bin/caddy"}, map[string]string{"/etc/caddy/Caddyfile": ":80 {\n\troot * /usr/share/caddy\n\tfile_server\n}\n"}},
		{"cron", nil, map[string]string{"/etc/crontab": etcCrontab}},
		{"dpkg", []string{"/etc/cron.daily/dpkg"}, nil},
		{"e2fsprogs", nil, map[string]string{"/etc/cron.d/e2scrub_all": e2scrub}},
		{"git", []string{"/usr/bin/git"}, nil},
		{"grub-pc", []string{"/usr/sbin/grub-install"}, nil},
		{"linux-generic-hwe-24.04", nil, nil},
		{"procps", []string{"/usr/bin/ps"}, map[string]string{"/etc/sysctl.conf": sysctlDefault, "/etc/sysctl.d/10-network-security.conf": netsec}},
		{"qemu-guest-agent", []string{"/usr/sbin/qemu-ga"}, nil},
		{"htop", []string{"/usr/bin/htop"}, nil},
		{"openssh-server", []string{"/usr/sbin/sshd"}, nil},
		{"paket-tool", []string{"/usr/local/bin/paket-tool"}, nil},
		{"ufw", nil, map[string]string{"/etc/ufw/ufw.conf": ufwDefault}},
	}
	var status strings.Builder
	for _, p := range pkgs {
		status.WriteString("Package: " + p.name + "\nStatus: install ok installed\nArchitecture: amd64\n")
		files := append([]string{}, p.files...)
		if len(p.conffiles) > 0 {
			status.WriteString("Conffiles:\n")
			var paths []string
			for f := range p.conffiles {
				paths = append(paths, f)
			}
			sort.Strings(paths)
			for _, f := range paths {
				status.WriteString(" " + f + " " + sum(p.conffiles[f]) + "\n")
				files = append(files, f)
			}
		}
		status.WriteString("Description: " + p.name + "\n\n")
		write("/var/lib/dpkg/info/"+p.name+".list", "/.\n/etc\n"+strings.Join(files, "\n")+"\n", 0o644)
	}
	// nginx ist wieder entfernt, nur noch die Konfiguration liegt da.
	status.WriteString("Package: nginx\nStatus: deinstall ok config-files\nConffiles:\n /etc/nginx/nginx.conf " + sum("x") + "\n\n")
	write("/var/lib/dpkg/status", status.String(), 0o644)
	write("/var/lib/ucf/hashfile", sum(sshdDefault)+"  /etc/ssh/sshd_config\n"+sum("GRUB_DEFAULT=0\n")+"  /etc/default/grub\n", 0o644)
}
